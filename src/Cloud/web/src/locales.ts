export type Locale = 'en' | 'zh-CN';
export const isLocale = (value: unknown): value is Locale => value === 'en' || value === 'zh-CN';
export function translate(locale: Locale, message: string): string {
  if (locale === 'en') return message;
  const key = message.trim();
  if (!Object.hasOwn(chinese, key)) return message;
  const translated = chinese[key];
  return translated === undefined ? message : message.replace(key, () => translated);
}
